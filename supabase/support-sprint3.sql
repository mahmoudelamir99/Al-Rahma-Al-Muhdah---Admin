--
--  الهدف: إضافة عمود "ملاحظة إدارية" (internal_note) لجدول طلبات الدعم،
--  عشان المدير العام يقدر يكتب ملاحظة داخلية على الطلب (مش بتظهر للموظف)،
--  وده مكمّل لزرار "تراجع" اللي بيفتح السكربت ده للمراجعة تاني.
--
--  السكربت آمن ويتشغّل أكتر من مرة (if not exists).
-- ============================================================================

-- ملاحظة إدارية داخلية — مش بتتعرض للموظف، للتوثيق/المراجعة الداخلية بس
alter table public.support_requests
  add column if not exists internal_note text;

comment on column public.support_requests.internal_note is
  'ملاحظة إدارية داخلية على الطلب تُكتب من المدير العام — لا تظهر للموظف';

-- ============================================================================
--  خلاص.
-- ============================================================================

select column_name, data_type
from information_schema.columns
where table_schema = 'public'
  and table_name = 'support_requests'
order by ordinal_position;
